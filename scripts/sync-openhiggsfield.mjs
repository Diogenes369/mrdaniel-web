#!/usr/bin/env node
/**
 * Copies the framework-free half of OpenHiggsfield AI's generation layer into
 * src/agent/openhiggsfield/, so our API routes can submit to the same platform with the same
 * model catalog and the same field mapping the studio uses.
 *
 * Why copy instead of import from vendor/: vendor/ is a gitignored clone (its own .git, its own
 * pnpm tree) and never reaches Vercel, so a deployed function importing from it would fail at
 * build time. The copied files are the pure ones only — catalog entries, the request mapper and
 * the queue client. Everything Next-shaped (server actions, the cookie jar, Zustand stores, the
 * React studio) stays upstream; our own wrapper lives in src/agent/OpenHiggsfieldEngine.ts.
 *
 *   node scripts/sync-openhiggsfield.mjs          refresh the copy from vendor/
 *   node scripts/sync-openhiggsfield.mjs --check   exit 1 if the copy has drifted (CI-friendly)
 *
 * Upstream: https://github.com/wide-trace/open-higgsfield
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const UPSTREAM = path.join(REPO_ROOT, 'vendor', 'open-higgsfield');
const FROM = path.join(UPSTREAM, 'src', 'generation');
const TO = path.join(REPO_ROOT, 'src', 'agent', 'openhiggsfield');

/** Pure modules: no `next`, no `react`, no store imports. Verified by assertPure() below. */
const FILES = ['credentials.ts', 'platform.ts', 'to-platform.ts'];
const DIRS = ['catalog'];
const FORBIDDEN = /from\s+["'](next|react|zustand|@vercel|\.\.\/stores|\.\/stores)/;

const check = process.argv.includes('--check');
const changed = [];

async function main() {
  await fs.access(FROM).catch(() => {
    throw new Error(
      `missing ${path.relative(REPO_ROOT, FROM)} — clone it first:\n` +
        '  git clone https://github.com/wide-trace/open-higgsfield vendor/open-higgsfield'
    );
  });

  const sources = [...FILES];
  for (const dir of DIRS) {
    for (const entry of await fs.readdir(path.join(FROM, dir))) {
      if (entry.endsWith('.ts')) sources.push(path.posix.join(dir, entry));
    }
  }

  for (const rel of sources.sort()) {
    const body = await fs.readFile(path.join(FROM, rel), 'utf8');
    assertPure(rel, body);
    const target = path.join(TO, rel);
    const existing = await fs.readFile(target, 'utf8').catch(() => null);
    if (existing === body) continue;
    changed.push(rel);
    if (check) continue;
    await fs.mkdir(path.dirname(target), { recursive: true });
    await fs.writeFile(target, body, 'utf8');
  }

  const readme = manifest(sources);
  const readmePath = path.join(TO, 'README.md');
  const currentReadme = await fs.readFile(readmePath, 'utf8').catch(() => null);
  if (stripCommit(currentReadme) !== stripCommit(readme)) {
    changed.push('README.md');
    if (!check) await fs.writeFile(readmePath, readme, 'utf8');
  }

  if (check) {
    if (changed.length === 0) return console.log(`in sync — ${sources.length} vendored files + manifest`);
    console.error(`drifted from upstream (${changed.length}):\n  ${changed.join('\n  ')}`);
    process.exitCode = 1;
    return;
  }
  console.log(
    changed.length === 0
      ? `already up to date — ${sources.length} files`
      : `synced ${changed.length} of ${sources.length} files:\n  ${changed.join('\n  ')}`
  );
}

/** A file that reaches for Next, React or a Zustand store cannot run inside a Vercel function
    here — catch that at sync time rather than at deploy time. */
function assertPure(rel, body) {
  const hit = body.match(FORBIDDEN);
  if (hit) throw new Error(`${rel} imports ${hit[1]} — it is no longer framework-free; do not copy it`);
}

function upstreamCommit() {
  try {
    return execFileSync('git', ['-C', UPSTREAM, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
  } catch {
    return 'unknown';
  }
}

function stripCommit(text) {
  return typeof text === 'string' ? text.replace(/^- upstream commit: .*$/m, '') : text;
}

function manifest(sources) {
  return `# Vendored from OpenHiggsfield AI — do not edit by hand

Generated by \`npm run sync:higgsfield\` (scripts/sync-openhiggsfield.mjs).

- upstream: https://github.com/wide-trace/open-higgsfield
- upstream commit: ${upstreamCommit()}
- files: ${sources.length}

These are the framework-free modules of the studio's generation layer: the 38-model catalog, the
per-model settings allow-lists, the request mapper (\`to-platform.ts\`) and the queue client
(\`platform.ts\`). Our wrapper is \`src/agent/OpenHiggsfieldEngine.ts\`; nothing else in this repo
should import these files directly.

Edits belong upstream. \`npm run sync:higgsfield -- --check\` fails if this copy has drifted, which
is what a refresh of vendor/open-higgsfield looks like from here.
`;
}

main().catch((err) => {
  console.error(String(err?.message ?? err));
  process.exitCode = 1;
});
