/**
 * Tech Tips slide painter — dark-cyber teaching slides, drawn on <canvas> so the SAME painter
 * feeds both outputs: the still carousel PNGs and every frame of the animated reel
 * (motionStudioService.ts). Size-agnostic: pass 1080×1350 for a 4:5 carousel or 1080×1920 for a
 * 9:16 reel and the layout scales off the canvas box rather than hard-coded coordinates.
 *
 * Backgrounds are OPTIONAL and generated by Pollinations (free, keyless, CORS-open — verified) from
 * each slide's own `visualPrompt`. Off by default: generation adds seconds per slide, and every
 * slide already reads correctly on the procedural obsidian+grid backdrop, which is the fallback
 * whenever generation is disabled, slow, or fails.
 */

const OBSIDIAN_TOP = '#06080D';
const OBSIDIAN_BOTTOM = '#0B0F17';
const CYBER_CYAN = '#22D3EE';
const SILVER = '#E2E8F0';
const DOMAIN = 'mrdaniel.co.il';

export interface SlideBox {
  W: number;
  H: number;
  PAD: number;
}

export function boxFor(width: number, height: number): SlideBox {
  return { W: width, H: height, PAD: Math.round(width * 0.085) };
}

// ─── background ─────────────────────────────────────────────────────────────────────────────

function hexToRgba(hex: string, a: number): string {
  const n = parseInt(hex.replace('#', ''), 16);
  return `rgba(${(n >> 16) & 255},${(n >> 8) & 255},${n & 255},${a})`;
}

function paintProceduralBackground(ctx: CanvasRenderingContext2D, b: SlideBox, seed: number) {
  const g = ctx.createLinearGradient(0, 0, b.W * 0.4, b.H);
  g.addColorStop(0, OBSIDIAN_TOP);
  g.addColorStop(1, OBSIDIAN_BOTTOM);
  ctx.fillStyle = g;
  ctx.fillRect(0, 0, b.W, b.H);

  // carbon grid
  ctx.save();
  ctx.strokeStyle = 'rgba(226,232,240,0.035)';
  ctx.lineWidth = 1;
  const step = Math.round(b.W / 10);
  for (let x = step; x < b.W; x += step) {
    ctx.beginPath();
    ctx.moveTo(x + 0.5, 0);
    ctx.lineTo(x + 0.5, b.H);
    ctx.stroke();
  }
  for (let y = step; y < b.H; y += step) {
    ctx.beginPath();
    ctx.moveTo(0, y + 0.5);
    ctx.lineTo(b.W, y + 0.5);
    ctx.stroke();
  }
  ctx.restore();

  // ambient accent glow, seeded so consecutive slides differ
  const cx = b.W * (0.3 + ((seed * 37) % 40) / 100);
  const cy = b.H * (0.25 + ((seed * 53) % 45) / 100);
  const rg = ctx.createRadialGradient(cx, cy, 0, cx, cy, b.W * 0.75);
  rg.addColorStop(0, hexToRgba(seed % 2 === 0 ? BRAND_GREEN : CYBER_CYAN, 0.14));
  rg.addColorStop(1, 'rgba(0,0,0,0)');
  ctx.fillStyle = rg;
  ctx.fillRect(0, 0, b.W, b.H);
}

/** Pollinations: free + keyless + `Access-Control-Allow-Origin: *` (verified), so the generated
 * image can be drawn to canvas without tainting it. */
export function pollinationsUrl(prompt: string, width: number, height: number, seed: number): string {
  const p = encodeURIComponent(prompt.slice(0, 380));
  return `https://image.pollinations.ai/prompt/${p}?width=${width}&height=${height}&nologo=true&seed=${seed}`;
}

/** Resolves one AI backdrop per slide. Bounded concurrency + per-image timeout; any failure just
 * yields null and the slide falls back to the procedural backdrop. */
export async function resolveTipBackgrounds(
  deck: TechTipDeck,
  width: number,
  height: number,
  onProgress?: (done: number, total: number) => void
): Promise<(HTMLImageElement | null)[]> {
  const total = deck.slides.length;
  const out: (HTMLImageElement | null)[] = new Array(total).fill(null);
  let done = 0;
  let cursor = 0;
  const workers = Array.from({ length: Math.min(3, total) }, async () => {
    while (cursor < total) {
      const i = cursor++;
      const slide = deck.slides[i];
      const prompt = slide.visualPrompt || 'abstract dark cyber technology grid, neon green accents, no text';
      out[i] = await Promise.race([
        loadImage(pollinationsUrl(prompt, Math.round(width / 2), Math.round(height / 2), i + 7)),
        new Promise<null>((r) => setTimeout(() => r(null), 30000)),
      ]);
      done++;
      onProgress?.(done, total);
    }
  });
  await Promise.all(workers);
  return out;
}

function drawBackgroundImage(ctx: CanvasRenderingContext2D, b: SlideBox, img: HTMLImageElement) {
  const iw = img.naturalWidth;
  const ih = img.naturalHeight;
  if (!iw || !ih) return;
  const canvasRatio = b.W / b.H;
  const imgRatio = iw / ih;
  let sw: number, sh: number, sx: number, sy: number;
  if (imgRatio > canvasRatio) {
    sh = ih;
    sw = sh * canvasRatio;
    sx = (iw - sw) / 2;
    sy = 0;
  } else {
    sw = iw;
    sh = sw / canvasRatio;
    sx = 0;
    sy = (ih - sh) / 2;
  }
  ctx.drawImage(img, sx, sy, sw, sh, 0, 0, b.W, b.H);
  // Heavy scrim: the AI backdrop is texture, never competition for the teaching content.
  ctx.fillStyle = 'rgba(6,8,13,0.78)';
  ctx.fillRect(0, 0, b.W, b.H);
}

// ─── chrome ─────────────────────────────────────────────────────────────────────────────────

function roundRectPath(ctx: CanvasRenderingContext2D, x: number, y: number, w: number, h: number, r: number) {
  const rr = Math.max(0, Math.min(r, w / 2, h / 2));
  ctx.beginPath();
  ctx.moveTo(x + rr, y);
  ctx.arcTo(x + w, y, x + w, y + h, rr);
  ctx.arcTo(x + w, y + h, x, y + h, rr);
  ctx.arcTo(x, y + h, x, y, rr);
  ctx.arcTo(x, y, x + w, y, rr);
  ctx.closePath();
}

function glassPanel(ctx: CanvasRenderingContext2D, x: number, y: number, w: number, h: number, r: number, accent?: string) {
  ctx.save();
  ctx.shadowColor = 'rgba(0,0,0,0.5)';
  ctx.shadowBlur = 36;
  ctx.shadowOffsetY = 18;
  roundRectPath(ctx, x, y, w, h, r);
  ctx.fillStyle = 'rgba(255,255,255,0.035)';
  ctx.fill();
  ctx.restore();
  roundRectPath(ctx, x, y, w, h, r);
  ctx.strokeStyle = accent ? hexToRgba(accent, 0.35) : 'rgba(255,255,255,0.10)';
  ctx.lineWidth = 1.5;
  ctx.stroke();
}

const setDisplay = (ctx: CanvasRenderingContext2D, px: number, w = 800) => {
  ctx.font = `${w} ${Math.round(px)}px Rubik, Heebo, sans-serif`;
};
const setBody = (ctx: CanvasRenderingContext2D, px: number, w = 400) => {
  ctx.font = `${w} ${Math.round(px)}px Heebo, Rubik, sans-serif`;
};
const setMono = (ctx: CanvasRenderingContext2D, px: number, w = 500) => {
  ctx.font = `${w} ${Math.round(px)}px 'JetBrains Mono', 'Heebo', monospace`;
};

function autoFit(
  ctx: CanvasRenderingContext2D,
  text: string,
  maxW: number,
  startPx: number,
  minPx: number,
  maxLines: number,
  set: (c: CanvasRenderingContext2D, px: number) => void
): { lines: string[]; px: number } {
  let px = startPx;
  let lines: string[] = [];
  for (let i = 0; i < 24; i++) {
    set(ctx, px);
    lines = wrapRtl(ctx, text, maxW);
    if (lines.length <= maxLines || px <= minPx) break;
    px = Math.max(minPx, px * 0.93);
  }
  return { lines, px };
}

function drawTopBar(ctx: CanvasRenderingContext2D, b: SlideBox, slide: TechTipSlide, index: number, total: number, logo: HTMLImageElement | null) {
  const y = Math.round(b.H * 0.045);
  // index, left (LTR)
  ctx.save();
  ctx.direction = 'ltr';
  ctx.textAlign = 'left';
  ctx.textBaseline = 'middle';
  setMono(ctx, b.W * 0.019, 600);
  ctx.fillStyle = 'rgba(226,232,240,0.55)';
  ctx.fillText(`${String(index + 1).padStart(2, '0')} / ${String(total).padStart(2, '0')}`, b.PAD, y);
  ctx.restore();

  // kicker chip, right (RTL)
  const kicker = sanitizeHebrewText(slide.kicker || '');
  if (kicker) {
    ctx.save();
    ctx.direction = 'rtl';
    ctx.textAlign = 'right';
    ctx.textBaseline = 'middle';
    setMono(ctx, b.W * 0.018, 600);
    const kw = ctx.measureText(kicker).width + b.W * 0.035;
    const kh = b.W * 0.038;
    const kx = b.W - b.PAD - kw;
    roundRectPath(ctx, kx, y - kh / 2, kw, kh, kh * 0.28);
    ctx.fillStyle = hexToRgba(BRAND_GREEN, 0.12);
    ctx.fill();
    ctx.strokeStyle = hexToRgba(BRAND_GREEN, 0.45);
    ctx.lineWidth = 1;
    ctx.stroke();
    ctx.fillStyle = '#9FE870';
    ctx.fillText(kicker, b.W - b.PAD - b.W * 0.017, y + 1);
    ctx.restore();
  }

  if (logo) {
    const h = b.W * 0.032;
    const w = h * (logo.naturalWidth / logo.naturalHeight || 3);
    ctx.save();
    ctx.globalAlpha = 0.85;
    ctx.drawImage(logo, b.W / 2 - w / 2, y - h / 2, w, h);
    ctx.restore();
  }
}

function drawBottomBar(ctx: CanvasRenderingContext2D, b: SlideBox, index: number, total: number) {
  const railY = b.H - b.PAD * 1.15;
  const gap = 7;
  const railW = b.W - b.PAD * 2;
  const segW = (railW - gap * (total - 1)) / total;
  for (let i = 0; i < total; i++) {
    const x = b.PAD + i * (segW + gap);
    roundRectPath(ctx, x, railY, Math.max(2, segW), 5, 2.5);
    ctx.fillStyle = i <= index ? BRAND_GREEN : 'rgba(255,255,255,0.14)';
    ctx.fill();
  }
  ctx.save();
  ctx.direction = 'ltr';
  ctx.textAlign = 'center';
  ctx.textBaseline = 'middle';
  setMono(ctx, b.W * 0.019, 600);
  ctx.fillStyle = 'rgba(226,232,240,0.6)';
  ctx.fillText(DOMAIN, b.W / 2, b.H - b.PAD * 0.5);
  ctx.restore();
}

