interface Region {
  x: number;
  y: number;
  w: number;
  h: number;
}

function contentRegion(b: SlideBox): Region {
  const top = b.H * 0.14;
  const bottom = b.H - b.PAD * 1.9;
  return { x: b.PAD, y: top, w: b.W - b.PAD * 2, h: bottom - top };
}

function drawTitle(ctx: CanvasRenderingContext2D, b: SlideBox, r: Region, title: string, startPx: number, maxLines: number): number {
  if (!title) return r.y;
  const { lines, px } = autoFit(ctx, sanitizeHebrewText(title), r.w, startPx, b.W * 0.032, maxLines, (c, p) => setDisplay(c, p, 800));
  setDisplay(ctx, px, 800);
  ctx.direction = 'rtl';
  ctx.textAlign = 'right';
  ctx.textBaseline = 'alphabetic';
  let y = r.y + px;
  for (const line of lines) {
    const grad = ctx.createLinearGradient(r.x + r.w, 0, r.x, 0);
    grad.addColorStop(0, '#FFFFFF');
    grad.addColorStop(0.6, SILVER);
    grad.addColorStop(1, CYBER_CYAN);
    ctx.fillStyle = grad;
    ctx.fillText(line, r.x + r.w, y);
    y += px * 1.18;
  }
  return y;
}

function drawParagraph(ctx: CanvasRenderingContext2D, b: SlideBox, r: Region, text: string, top: number, maxH: number) {
  if (!text) return;
  const { lines, px } = autoFit(ctx, sanitizeHebrewText(text), r.w - b.W * 0.06, b.W * 0.038, b.W * 0.022, 14, (c, p) => setBody(c, p, 400));
  const lh = px * 1.55;
  const panelH = Math.min(maxH, lines.length * lh + b.W * 0.075);
  glassPanel(ctx, r.x, top, r.w, panelH, b.W * 0.028);
  setBody(ctx, px, 400);
  ctx.fillStyle = 'rgba(255,255,255,0.94)';
  ctx.direction = 'rtl';
  ctx.textAlign = 'right';
  let y = top + b.W * 0.045 + px;
  for (const line of lines) {
    if (y > top + panelH - b.W * 0.01) break;
    ctx.fillText(line, r.x + r.w - b.W * 0.03, y);
    y += lh;
  }
}

function drawCodeBlock(ctx: CanvasRenderingContext2D, b: SlideBox, r: Region, slide: TechTipSlide, top: number, maxH: number) {
  const lines = highlightCode(slide.code, slide.codeLang);
  const panelH = maxH;
  glassPanel(ctx, r.x, top, r.w, panelH, b.W * 0.024, CYBER_CYAN);

  // window chrome + language tag
  ctx.save();
  for (let i = 0; i < 3; i++) {
    ctx.beginPath();
    ctx.arc(r.x + b.W * 0.032 + i * b.W * 0.022, top + b.W * 0.032, b.W * 0.0055, 0, Math.PI * 2);
    ctx.fillStyle = ['#F87171', '#FBBF24', '#34D399'][i];
    ctx.fill();
  }
  ctx.direction = 'ltr';
  ctx.textAlign = 'right';
  ctx.textBaseline = 'middle';
  setMono(ctx, b.W * 0.017, 700);
  ctx.fillStyle = hexToRgba(CYBER_CYAN, 0.85);
  ctx.fillText((slide.codeLang || 'code').toUpperCase(), r.x + r.w - b.W * 0.028, top + b.W * 0.032);
  ctx.restore();

  // Fit the snippet: shrink until every line fits both the panel height AND its width.
  const innerTop = top + b.W * 0.062;
  const innerH = panelH - b.W * 0.078;
  const innerW = r.w - b.W * 0.075;
  let px = b.W * 0.026;
  const minPx = b.W * 0.0135;
  for (let i = 0; i < 24; i++) {
    setMono(ctx, px, 500);
    const widest = lines.reduce((m, toks) => Math.max(m, ctx.measureText(toks.map((t) => t.text).join('')).width), 0);
    if ((lines.length * px * 1.5 <= innerH && widest <= innerW) || px <= minPx) break;
    px = Math.max(minPx, px * 0.94);
  }
  setMono(ctx, px, 500);
  const lh = px * 1.5;

  ctx.save();
  ctx.direction = 'ltr';
  ctx.textAlign = 'left';
  ctx.textBaseline = 'alphabetic';
  let y = innerTop + px;
  const gutterW = px * 2.2;
  for (let i = 0; i < lines.length; i++) {
    if (y > innerTop + innerH) break;
    // line number gutter
    ctx.fillStyle = 'rgba(148,163,184,0.35)';
    ctx.fillText(String(i + 1).padStart(2, ' '), r.x + b.W * 0.028, y);
    // tokens
    let x = r.x + b.W * 0.028 + gutterW;
    for (const tok of lines[i]) {
      ctx.fillStyle = TOKEN_PALETTE[tok.color];
      ctx.fillText(tok.text, x, y);
      x += ctx.measureText(tok.text).width;
    }
    y += lh;
  }
  ctx.restore();
}

function drawBulletList(ctx: CanvasRenderingContext2D, b: SlideBox, r: Region, bullets: string[], top: number, maxH: number, marker: 'check' | 'dot') {
  const items = bullets.slice(0, 5);
  if (!items.length) return;
  const rowH = Math.min(b.W * 0.16, maxH / items.length);
  let y = top;
  for (const raw of items) {
    const h = rowH - b.W * 0.014;
    glassPanel(ctx, r.x, y, r.w, h, b.W * 0.02);
    const boxS = b.W * 0.037;
    const bx = r.x + r.w - b.W * 0.032 - boxS;
    const by = y + h / 2 - boxS / 2;
    if (marker === 'check') {
      roundRectPath(ctx, bx, by, boxS, boxS, boxS * 0.25);
      ctx.fillStyle = hexToRgba(BRAND_GREEN, 0.16);
      ctx.fill();
      ctx.strokeStyle = BRAND_GREEN;
      ctx.lineWidth = 2;
      ctx.stroke();
      ctx.save();
      ctx.strokeStyle = BRAND_GREEN;
      ctx.lineWidth = boxS * 0.11;
      ctx.lineCap = 'round';
      ctx.beginPath();
      ctx.moveTo(bx + boxS * 0.26, by + boxS * 0.52);
      ctx.lineTo(bx + boxS * 0.45, by + boxS * 0.72);
      ctx.lineTo(bx + boxS * 0.76, by + boxS * 0.3);
      ctx.stroke();
      ctx.restore();
    } else {
      ctx.beginPath();
      ctx.arc(bx + boxS / 2, by + boxS / 2, boxS * 0.22, 0, Math.PI * 2);
      ctx.fillStyle = CYBER_CYAN;
      ctx.fill();
    }
    ctx.direction = 'rtl';
    ctx.textAlign = 'right';
    ctx.textBaseline = 'alphabetic';
    const { lines, px } = autoFit(ctx, sanitizeHebrewText(raw), r.w - boxS - b.W * 0.09, b.W * 0.03, b.W * 0.02, 2, (c, p) => setBody(c, p, 500));
    setBody(ctx, px, 500);
    ctx.fillStyle = 'rgba(255,255,255,0.95)';
    let ty = y + h / 2 - ((lines.length - 1) * px * 1.3) / 2 + px * 0.34;
    for (const line of lines) {
      ctx.fillText(line, bx - b.W * 0.022, ty);
      ty += px * 1.3;
    }
    y += rowH;
  }
}

function drawStepBadge(ctx: CanvasRenderingContext2D, b: SlideBox, r: Region, n: number): number {
  const size = b.W * 0.115;
  const x = r.x + r.w - size;
  const y = r.y;
  ctx.save();
  roundRectPath(ctx, x, y, size, size, size * 0.28);
  ctx.fillStyle = hexToRgba(BRAND_GREEN, 0.14);
  ctx.fill();
  ctx.strokeStyle = hexToRgba(BRAND_GREEN, 0.55);
  ctx.lineWidth = 2;
  ctx.stroke();
  ctx.direction = 'ltr';
  ctx.textAlign = 'center';
  ctx.textBaseline = 'middle';
  setDisplay(ctx, size * 0.52, 900);
  ctx.fillStyle = BRAND_GREEN;
  ctx.shadowColor = BRAND_GREEN;
  ctx.shadowBlur = 18;
  ctx.fillText(String(n), x + size / 2, y + size / 2 + 2);
  ctx.restore();
  return y + size + b.W * 0.03;
}

