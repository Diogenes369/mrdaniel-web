// Regenerates src/lib/brandLogoPaths.generated.ts from the `simple-icons` devDependency (CC0).
//
// A generated, committed file rather than a runtime import: the package ships ~3,400 icons in one
// module, and a future release that drops a brand (OpenAI and Canva are already gone) would break
// the build instead of just leaving that tool on its geometric fallback mark.
//
// Usage (from dashboard/):  npm run sync:logos
import { writeFileSync } from 'node:fs';
import * as icons from 'simple-icons';

/** ToolBrand → Simple Icons export name. A brand missing upstream keeps its hand-drawn mark. */
const WANT = {
  gemini: 'siGooglegemini',
  claude: 'siClaude',
  notebooklm: 'siNotebooklm',
  make: 'siMake',
  n8n: 'siN8n',
  perplexity: 'siPerplexity',
  copilot: 'siGithubcopilot',
  vercel: 'siVercel',
  python: 'siPython',
  react: 'siReact',
  meta: 'siMeta',
  nextjs: 'siNextdotjs',
  typescript: 'siTypescript',
  docker: 'siDocker',
  github: 'siGithub',
  cursor: 'siCursor',
  supabase: 'siSupabase',
  firebase: 'siFirebase',
  cloudflare: 'siCloudflare',
};

const rows = [];
for (const [brand, key] of Object.entries(WANT)) {
  const icon = icons[key];
  if (!icon) {
    console.warn(`simple-icons no longer ships ${key} — ${brand} falls back to its geometric mark`);
    continue;
  }
  rows.push(`  ${brand}: { title: ${JSON.stringify(icon.title)}, hex: '#${icon.hex}', path: ${JSON.stringify(icon.path)} },`);
}

const out = `// GENERATED by scripts/sync-brand-logos.mjs from simple-icons (CC0-1.0). Do not edit by hand.
import type { ToolBrand } from './techTipsApi';

/** Single-path brand logos in a 24×24 viewBox, drawn with Path2D so the export canvas stays untainted. */
export const BRAND_LOGO_PATHS: Partial<Record<ToolBrand, { title: string; hex: string; path: string }>> = {
${rows.join('\n')}
};
`;
writeFileSync(new URL('../src/lib/brandLogoPaths.generated.ts', import.meta.url), out);
console.log(`wrote ${rows.length} logos`);
